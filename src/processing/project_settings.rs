#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EditorBuildSettingsLimits {
    pub max_scenes: usize,
    pub max_total_path_bytes: usize,
}

impl Default for EditorBuildSettingsLimits {
    fn default() -> Self {
        Self {
            max_scenes: 65_536,
            max_total_path_bytes: 16 * 1024 * 1024,
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EditorBuildSettingsError {
    SceneCountLimitExceeded {
        count: usize,
        limit: usize,
    },
    PathByteCountOverflow,
    TotalPathBytesLimitExceeded {
        byte_count: usize,
        limit: usize,
    },
    AllocationFailed {
        resource: &'static str,
        requested: usize,
    },
}

impl Display for EditorBuildSettingsError {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        match self {
            Self::SceneCountLimitExceeded { count, limit } => {
                write!(
                    f,
                    "EditorBuildSettings has {count} scenes, exceeding limit {limit}"
                )
            }
            Self::PathByteCountOverflow => {
                f.write_str("EditorBuildSettings scene path byte count overflows")
            }
            Self::TotalPathBytesLimitExceeded { byte_count, limit } => write!(
                f,
                "EditorBuildSettings scene paths use {byte_count} bytes, exceeding limit {limit}"
            ),
            Self::AllocationFailed {
                resource,
                requested,
            } => write!(f, "could not allocate {requested} entries for {resource}"),
        }
    }
}

impl Error for EditorBuildSettingsError {}

impl EditorBuildSettingsModel {
    /// Copies source `BuildSettings.Scenes` in order and enables every generated scene entry.
    pub fn from_build_settings_paths(
        paths: &[String],
        limits: EditorBuildSettingsLimits,
    ) -> Result<Self, EditorBuildSettingsError> {
        if paths.len() > limits.max_scenes {
            return Err(EditorBuildSettingsError::SceneCountLimitExceeded {
                count: paths.len(),
                limit: limits.max_scenes,
            });
        }

        let mut total_path_bytes = 0usize;
        for path in paths {
            total_path_bytes = total_path_bytes
                .checked_add(path.len())
                .ok_or(EditorBuildSettingsError::PathByteCountOverflow)?;
            if total_path_bytes > limits.max_total_path_bytes {
                return Err(EditorBuildSettingsError::TotalPathBytesLimitExceeded {
                    byte_count: total_path_bytes,
                    limit: limits.max_total_path_bytes,
                });
            }
        }

        let mut scenes = Vec::new();
        scenes.try_reserve_exact(paths.len()).map_err(|_| {
            EditorBuildSettingsError::AllocationFailed {
                resource: "EditorBuildSettings scene entries",
                requested: paths.len(),
            }
        })?;
        for path in paths {
            let mut owned_path = String::new();
            owned_path.try_reserve_exact(path.len()).map_err(|_| {
                EditorBuildSettingsError::AllocationFailed {
                    resource: "EditorBuildSettings scene path",
                    requested: path.len(),
                }
            })?;
            owned_path.push_str(path);
            scenes.push(EditorBuildSettingsScene {
                enabled: true,
                path: owned_path,
            });
        }
        Ok(Self { scenes })
    }

    pub fn scenes(&self) -> &[EditorBuildSettingsScene] {
        &self.scenes
    }
}

/// `WebGLLinkerTarget.Wasm`, written to `webGLLinkerTarget` when the field is present.
pub const WEB_GL_LINKER_TARGET_WASM: i32 = 1;
/// `ApiCompatibilityLevel.NET_2_0`, for assemblies carrying mscorlib 2.
pub const API_COMPATIBILITY_LEVEL_NET_2_0: i32 = 2;
/// `ApiCompatibilityLevel.NET_Unity_4_8`, for modern assemblies.
pub const API_COMPATIBILITY_LEVEL_NET_UNITY_4_8: i32 = 5;
/// `ScriptingRuntimeVersion.Legacy`, for assemblies carrying mscorlib 2.
pub const SCRIPTING_RUNTIME_VERSION_LEGACY: i32 = 0;
/// `ScriptingRuntimeVersion.Latest`, for modern assemblies.
pub const SCRIPTING_RUNTIME_VERSION_LATEST: i32 = 1;

/// Editor values for a `TypeTreeObject{ IsPlayerSettings }` asset, mirroring the
/// `EditorFormatProcessor.Convert` arm: `webGLLinkerTarget` is forced to Wasm and
/// `allowUnsafeCode` to true, while the scripting pair follows `HasMscorlib2`.
///
/// Field presence (`ContainsField`) stays caller-side; this kernel answers what to write.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PlayerSettingsEditorValues {
    pub web_gl_linker_target: i32,
    pub allow_unsafe_code: bool,
    pub api_compatibility_level: i32,
    pub scripting_runtime_version: i32,
}

/// The PlayerSettings scripting decision: mscorlib-2 assemblies keep the legacy pair,
/// everything else moves to the latest pair.
pub fn player_settings_editor_values(has_mscorlib2: bool) -> PlayerSettingsEditorValues {
    let (api_compatibility_level, scripting_runtime_version) = if has_mscorlib2 {
        (
            API_COMPATIBILITY_LEVEL_NET_2_0,
            SCRIPTING_RUNTIME_VERSION_LEGACY,
        )
    } else {
        (
            API_COMPATIBILITY_LEVEL_NET_UNITY_4_8,
            SCRIPTING_RUNTIME_VERSION_LATEST,
        )
    };
    PlayerSettingsEditorValues {
        web_gl_linker_target: WEB_GL_LINKER_TARGET_WASM,
        allow_unsafe_code: true,
        api_compatibility_level,
        scripting_runtime_version,
    }
}

#[cfg(test)]
mod tests {
    use super::{
        AssetPipelineMode, CacheServerMode, CollabEditorSettingsDefaults, EditorBuildSettingsError,
        EditorBuildSettingsLimits, EditorBuildSettingsModel, EditorSerializationMode,
        EditorSettingsCapabilities, EditorSettingsModel, EnterPlayModeOptions,
        ExternalVersionControlSupportMode,
    };

    #[test]
    fn editor_build_settings_preserves_source_order_duplicates_and_enabled_state() {
        let source_paths = vec![
            "Assets/Scenes/First".to_owned(),
            "Packages/Worlds/Second".to_owned(),
            "Assets/Scenes/First".to_owned(),
        ];
        let settings = EditorBuildSettingsModel::from_build_settings_paths(
            &source_paths,
            EditorBuildSettingsLimits::default(),
        )
        .unwrap();

        assert_eq!(
            settings
                .scenes()
                .iter()
                .map(|scene| (scene.enabled, scene.path.as_str()))
                .collect::<Vec<_>>(),
            [
                (true, "Assets/Scenes/First"),
                (true, "Packages/Worlds/Second"),
                (true, "Assets/Scenes/First"),
            ]
        );
        assert_eq!(source_paths[0], settings.scenes()[0].path);
    }

    #[test]
    fn editor_build_settings_checks_scene_and_aggregate_path_limits() {
        let paths = vec!["a".to_owned(), "bc".to_owned()];
        assert_eq!(
            EditorBuildSettingsModel::from_build_settings_paths(
                &paths,
                EditorBuildSettingsLimits {
                    max_scenes: 1,
                    ..EditorBuildSettingsLimits::default()
                }
            ),
            Err(EditorBuildSettingsError::SceneCountLimitExceeded { count: 2, limit: 1 })
        );
        assert_eq!(
            EditorBuildSettingsModel::from_build_settings_paths(
                &paths,
                EditorBuildSettingsLimits {
                    max_total_path_bytes: 2,
                    ..EditorBuildSettingsLimits::default()
                }
            ),
            Err(EditorBuildSettingsError::TotalPathBytesLimitExceeded {
                byte_count: 3,
                limit: 2,
            })
        );
    }

    #[test]
    fn editor_settings_defaults_match_the_source_extension_values() {
        let settings = EditorSettingsModel::source_defaults(EditorSettingsCapabilities {
            collab_editor_settings: true,
            asset_pipeline_mode: true,
        });
        assert_eq!(
            settings,
            EditorSettingsModel {
                external_version_control_support_text: "Visible Meta Files",
                external_version_control_support_mode: ExternalVersionControlSupportMode::Generic,
                serialization_mode: EditorSerializationMode::ForceText,
                serialize_inline_mappings_on_one_line: true,
                sprite_packer_padding_power: 1,
                etc_texture_compressor_behavior: 1,
                etc_texture_fast_compressor: 1,
                etc_texture_normal_compressor: 2,
                etc_texture_best_compressor: 4,
                project_generation_included_extensions: "txt;xml;fnt;cd;asmdef;rsp;asmref",
                project_generation_root_namespace: "",
                collab_editor_settings: Some(CollabEditorSettingsDefaults {
                    in_progress_enabled: true,
                }),
                user_generated_project_suffix: "",
                enable_texture_streaming_in_edit_mode: true,
                enable_texture_streaming_in_play_mode: true,
                async_shader_compilation: true,
                asset_pipeline_mode: Some(AssetPipelineMode::Version2),
                cache_server_mode: CacheServerMode::AsPreferences,
                cache_server_endpoint: "",
                cache_server_namespace_prefix: "default",
                cache_server_enable_download: true,
                cache_server_enable_upload: true,
                show_lightmap_resolution_overlay: true,
                use_legacy_probe_sample_count: true,
                enter_play_mode_options: EnterPlayModeOptions {
                    disable_domain_reload: true,
                    disable_scene_reload: true,
                },
            }
        );
    }

    #[test]
    fn editor_settings_defaults_respect_optional_field_capabilities() {
        let settings = EditorSettingsModel::source_defaults(EditorSettingsCapabilities {
            collab_editor_settings: false,
            asset_pipeline_mode: false,
        });
        assert_eq!(settings.collab_editor_settings, None);
        assert_eq!(settings.asset_pipeline_mode, None);
    }

    #[test]
    fn player_settings_editor_values_follow_the_mscorlib_branch() {
        assert_eq!(
            super::player_settings_editor_values(true),
            super::PlayerSettingsEditorValues {
                web_gl_linker_target: super::WEB_GL_LINKER_TARGET_WASM,
                allow_unsafe_code: true,
                api_compatibility_level: super::API_COMPATIBILITY_LEVEL_NET_2_0,
                scripting_runtime_version: super::SCRIPTING_RUNTIME_VERSION_LEGACY,
            }
        );
        assert_eq!(
            super::player_settings_editor_values(false),
            super::PlayerSettingsEditorValues {
                web_gl_linker_target: 1,
                allow_unsafe_code: true,
                api_compatibility_level: super::API_COMPATIBILITY_LEVEL_NET_UNITY_4_8,
                scripting_runtime_version: super::SCRIPTING_RUNTIME_VERSION_LATEST,
            }
        );
        // The unconditional fields match the source literals on both branches.
        for values in [
            super::player_settings_editor_values(true),
            super::player_settings_editor_values(false),
        ] {
            assert_eq!(values.web_gl_linker_target, 1);
            assert!(values.allow_unsafe_code);
        }
        // Discriminants pin the UnityEditor enum values documented above.
        assert_eq!(super::API_COMPATIBILITY_LEVEL_NET_2_0, 2);
        assert_eq!(super::API_COMPATIBILITY_LEVEL_NET_UNITY_4_8, 5);
        assert_eq!(super::SCRIPTING_RUNTIME_VERSION_LEGACY, 0);
        assert_eq!(super::SCRIPTING_RUNTIME_VERSION_LATEST, 1);
    }
}
